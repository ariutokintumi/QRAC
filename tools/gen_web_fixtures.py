import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from qrac import authorization as auth  # noqa: E402
from qrac import derive, lms  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, ".."))
OUT = os.path.join(ROOT, "apps", "web", "test", "fixtures.json")


def h(b: bytes) -> str:
    return "0x" + b.hex()


def main():
    words = derive.load_wordlist()
    fx = {"note": "Generated by tools/gen_web_fixtures.py from the Python references. Do not edit."}

    # SHA-256 around block boundaries
    import hashlib
    fx["sha256"] = []
    for n in (0, 1, 3, 54, 55, 56, 63, 64, 65, 86, 119, 120, 127, 128, 129, 1000):
        data = bytes((i * 7 + n) % 256 for i in range(n))
        fx["sha256"].append({"data": h(data), "digest": h(hashlib.sha256(data).digest())})

    # BIP-39 official vectors (24 words, passphrase TREZOR)
    fx["bip39"] = json.load(open(os.path.join(HERE, "vectors", "bip39.json"), encoding="utf-8"))["vectors"]

    # QRAC derivation from a fixed test mnemonic (empty passphrase, as QRAC uses)
    mnemonic = derive.entropy_to_mnemonic(bytes([0x11] * 32), words)
    seed64 = derive.mnemonic_to_seed(mnemonic)
    fx["derivation"] = {"mnemonic": mnemonic, "bip39Seed": h(seed64), "trees": []}
    for chain_id, idx, epoch in ((11155111, 0, 0), (11155111, 0, 1), (11155111, 1, 0), (131277322940537, 3, 7)):
        s, i = derive.derive_tree(seed64, chain_id, idx, epoch)
        fx["derivation"]["trees"].append({"chainId": str(chain_id), "accountIndex": idx, "epoch": epoch,
                                          "seed": h(s), "I": h(i)})

    # LMS: small tree (H5/W4) fully checked, plus one production-size tree (H10/W4) public key
    s, i = derive.derive_tree(seed64, 11155111, 0, 0)
    small = lms.lms_keygen(5, lms.LMOTS_SHA256_N32_W4, i, s)
    msgs = [b"", b"QRAC", bytes(range(256)) * 3]
    fx["lms_small"] = {
        "lmsType": 5, "otsType": 3, "seed": h(s), "I": h(i), "publicKey": h(small.public_key()),
        "signatures": [{"leaf": q, "message": h(m), "signature": h(small.sign(q, m))}
                       for q, m in ((0, msgs[0]), (7, msgs[1]), (31, msgs[2]))],
    }
    big = lms.lms_keygen(lms.LMS_SHA256_M32_H10, lms.LMOTS_SHA256_N32_W4, i, s)
    fx["lms_h10"] = {"lmsType": 6, "otsType": 3, "seed": h(s), "I": h(i), "publicKey": h(big.public_key()),
                     "signature": {"leaf": 777, "message": h(b"QRAC H10"), "signature": h(big.sign(777, b"QRAC H10"))}}

    # RFC 8554 Test Case 2 top tree (H10/W4): seed, I, expected public key and q=3 signature
    rfc = json.load(open(os.path.join(HERE, "vectors", "rfc8554.json")))["vectors"]
    top = rfc["tc2_private_key"]["top"]
    sig = bytes.fromhex(rfc["tc2_signature"])
    l0 = lms.lms_signature_length(6, 3)
    fx["rfc8554_tc2_top"] = {"seed": "0x" + top["SEED"], "I": "0x" + top["I"],
                             "publicKey": "0x" + rfc["tc2_public_key"][8:],
                             "message": h(sig[4 + l0:4 + l0 + 56]), "signature": h(sig[4:4 + l0])}

    # Authorization message encoding
    acct = "0x1111111111111111111111111111111111111111"
    payload = auth.execute_payload([
        auth.Call("0x2222222222222222222222222222222222222222", 10**18, b""),
        auth.Call("0x3333333333333333333333333333333333333333", 0, bytes.fromhex("a9059cbb") + bytes(64), True),
    ])
    header = auth.Header(2, 5, auth.KIND_EXECUTE, "0x4444444444444444444444444444444444444444", 100, 2**40)
    fx["authorization"] = {
        "chainId": "11155111", "account": acct, "leaf": 513,
        "header": {"epoch": 2, "nonce": 5, "kind": 1, "allowedSubmitter": header.allowed_submitter,
                   "validAfter": 100, "validUntil": str(2**40)},
        "calls": [
            {"target": "0x2222222222222222222222222222222222222222", "value": str(10**18), "data": "0x",
             "checkReturn": False},
            {"target": "0x3333333333333333333333333333333333333333", "value": "0",
             "data": "0xa9059cbb" + "00" * 64, "checkReturn": True},
        ],
        "payload": h(payload),
        "message": h(auth.message(11155111, acct, header, 513, payload)),
        "rotatePayload": h(auth.rotate_payload(small.public_key(), 3)),
    }

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(fx, f, indent=1)
        f.write("\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
